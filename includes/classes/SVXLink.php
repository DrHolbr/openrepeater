	public function delete_custom_evnets() {
		$sample = $this->configDestination('ORP_placeholder.tcl');
		if ($sample === null) {
			return;
		}
		$dir = dirname($sample);
		if (!is_dir($dir) || is_link($dir) || !BenchGuard::componentsAreReal($dir)) {
			return;
		}
		$files = glob($dir . '/ORP_*');
		if ($files) {
			foreach ($files as $file) {
				if (is_link($file) || !is_file($file)) {
					continue;
				}
				unlink($file);
			}
		}
	}


