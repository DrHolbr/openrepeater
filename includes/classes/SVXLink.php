	public function build_rx($curPort) {
		if (BenchGuard::detect()->operatingMode() === 'functional-test') {
			$cfg = $this->disconnectedRuntimeConfig();
			return array('Rx1' => $cfg['Rx1']);
		}
		list($audioDevice, $audioChannel) = $this->audioDeviceParts($this->portsArray[$curPort]['rxAudioDev']);
		
		$rx_array['RX_Port'.$curPort] = [
			'TYPE' => 'Local',
			'AUDIO_DEV' => $audioDevice,
			'AUDIO_CHANNEL' => $audioChannel,
		];
	
		if (strtolower($this->portsArray[$curPort]['rxMode']) == 'vox') {
			// VOX Squelch Mode
			$rx_array['RX_Port'.$curPort] += [
				'SQL_DET' => $this->settingsArray['rxTone'] ? 'CTCSS' : 'VOX',
				'VOX_FILTER_DEPTH' => '150',
				'VOX_THRESH' => '300',
				'SQL_HANGTIME' => '1000',
			];

		} else {
			// COS Squelch Mode
			$rx_array['RX_Port'.$curPort] += [
				'SQL_DET' => $this->settingsArray['rxTone'] ? 'CTCSS' : 'GPIO',
				'GPIO_SQL_PIN' => 'gpio' . $this->portsArray[$curPort]['rxGPIO'],
				'SQL_HANGTIME' => '10',
			];
		}

		if ($this->settingsArray['rxTone']) {
			$rx_array['RX_Port'.$curPort] += [
				'CTCSS_FQ' => $this->settingsArray['rxTone'],
				'CTCSS_OPEN_THRESH' => $this->settingsArray['rxCtcssOpenThresh'] ?: '10',
				'CTCSS_CLOSE_THRESH' => $this->settingsArray['rxCtcssCloseThresh'] ?: '5',
			];
		}

		$rx_array['RX_Port'.$curPort] += [
			'SQL_START_DELAY' => '1',
			'SQL_DELAY' => '10',
			'SIGLEV_SLOPE' => '1',
			'SIGLEV_OFFSET' => '0',
			'SIGLEV_OPEN_THRESH' => '30',
			'SIGLEV_CLOSE_THRESH' => '10',
			'DEEMPHASIS' => '1',
			'PEAK_METER' => '0',
			'DTMF_DEC_TYPE' => 'INTERNAL',
			'DTMF_MUTING' => '1',
			'DTMF_HANGTIME' => '100',
			'DTMF_SERIAL' => '/dev/ttyS0',
		];
	
		return $rx_array;
	}



